export type UiV2MessageKey = keyof typeof messages.en;

export function translate(locale: UiV2Locale, key: UiV2MessageKey): string {
  return messages[locale][key] ?? messages.en[key] ?? key;
}

export function isUiV2Locale(value: string | null): value is UiV2Locale {
  return value === 'pt-PT' || value === 'en';
}

export function formatUiV2Date(value: string | null | undefined, locale: UiV2Locale) {
  if (!value) {
    return translate(locale, 'value.notAvailable');
  }

  const date = new Date(value);
  if (Number.isNaN(date.getTime())) {
    return value;
  }

  return new Intl.DateTimeFormat(locale, {
    dateStyle: 'medium',
    timeStyle: 'short',
  }).format(date);
}

export function formatUiV2Number(value: number | null | undefined, locale: UiV2Locale, maximumFractionDigits = 2) {
  if (value === null || value === undefined || Number.isNaN(value)) {
    return translate(locale, 'value.notAvailable');
  }

  return new Intl.NumberFormat(locale, {
    maximumFractionDigits,
  }).format(value);
}
