export type UiMessageKey = keyof typeof messages.en;

export function translate(locale: UiLocale, key: UiMessageKey): string {
  return messages[locale][key] ?? messages.en[key] ?? key;
}

export function isUiLocale(value: string | null): value is UiLocale {
  return value === 'pt-PT' || value === 'en';
}

export function formatUiDate(value: string | null | undefined, locale: UiLocale) {
  if (!value) {
    return translate(locale, 'value.notAvailable');
  }

  const date = new Date(value);
  if (Number.isNaN(date.getTime())) {
    return value;
  }

  return new Intl.DateTimeFormat(locale, {
    dateStyle: 'medium',
    timeStyle: 'short',
  }).format(date);
}

export function formatUiNumber(value: number | null | undefined, locale: UiLocale, maximumFractionDigits = 2) {
  if (value === null || value === undefined || Number.isNaN(value)) {
    return translate(locale, 'value.notAvailable');
  }

  return new Intl.NumberFormat(locale, {
    maximumFractionDigits,
  }).format(value);
}
